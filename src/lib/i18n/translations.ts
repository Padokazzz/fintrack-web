type Widen<T> = T extends (...args: infer Args) => infer Return
  ? (...args: Args) => Return
  : T extends readonly (infer Item)[]
    ? readonly Widen<Item>[]
    : T extends string
      ? string
      : T extends object
        ? { [Key in keyof T]: Widen<T[Key]> }
        : T;

export type TranslationDictionary = Widen<(typeof translations)["en"]>;
